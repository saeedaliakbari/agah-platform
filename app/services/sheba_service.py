def detect_bank_name(sheba_number: str) -> str:
    """نام بانک را از روی کد بانک داخل شماره شبا تشخیص می‌دهد."""
    normalized = sheba_number.strip().upper().replace(" ", "")
    if normalized.startswith("IR"):
        normalized = normalized[2:]

    if len(normalized) < 5:
        return "نامشخص"

    bank_code = normalized[2:5]
    return IRAN_BANK_CODES.get(bank_code, "نامشخص")